"""Keys, tokens and a stub key source for the Entra variant's tests.

Tokens are signed with RSA key pairs generated by the test run. The verifier is
handed a stub key source that serves the public half, so no tenant and no network
are involved.
"""

import base64
import hashlib
import hmac
import json
import time
from collections.abc import Mapping, Sequence
from functools import cache

import jwt
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.rsa import (
    RSAPrivateKey,
    generate_private_key,
)
from jwt.exceptions import PyJWKClientError

from app.infrastructure.auth.entra import EntraTokenVerifier
from app.infrastructure.auth.entra_jwks import CooldownSigningKeyResolver
from tests.auth_test_env import TEST_API_CLIENT_ID, TEST_TENANT_ID

RSA_PUBLIC_EXPONENT = 65537
RSA_KEY_SIZE = 2048
SIGNING_KID = "test-signing-kid"
AUTHORITY = "https://login.microsoftonline.com"
ISSUER = f"{AUTHORITY}/{TEST_TENANT_ID}/v2.0"
OBJECT_ID = "a1b2c3d4-0000-4000-8000-00000000abcd"
USERNAME = "jane.doe@example.com"
USER_EMAIL = "jane.doe.mail@example.com"
SCOPE_NAME = "access_as_user"
TOKEN_LIFETIME_SECONDS = 3600
REFRESH_COOLDOWN_SECONDS = 30.0


def generate_signing_key() -> RSAPrivateKey:
    """Create an RSA private key for signing test tokens."""
    return generate_private_key(
        public_exponent=RSA_PUBLIC_EXPONENT, key_size=RSA_KEY_SIZE
    )


@cache
def tenant_signing_key() -> RSAPrivateKey:
    """The key the test tenant publishes; generated once, because that is slow."""
    return generate_signing_key()


@cache
def unpublished_signing_key() -> RSAPrivateKey:
    """A key the test tenant never published, for forging signatures."""
    return generate_signing_key()


def valid_claims(**overrides: object) -> dict[str, object]:
    """Claims of an access token the verifier accepts.

    Args:
        **overrides: Claims to replace. A value of ``None`` removes the claim,
            which is how tests model a missing one.

    Returns:
        The claim set, issued now and valid for an hour.
    """
    now = int(time.time())
    claims: dict[str, object] = {
        "iss": ISSUER,
        "aud": TEST_API_CLIENT_ID,
        "tid": TEST_TENANT_ID,
        "oid": OBJECT_ID,
        "preferred_username": USERNAME,
        "scp": SCOPE_NAME,
        "iat": now,
        "exp": now + TOKEN_LIFETIME_SECONDS,
    }
    claims.update(overrides)
    return {name: value for name, value in claims.items() if value is not None}


def sign_token(
    claims: Mapping[str, object],
    private_key: RSAPrivateKey,
    *,
    kid: str = SIGNING_KID,
    algorithm: str = "RS256",
) -> str:
    """Sign claims as a token whose header names ``kid``; RS256 by default."""
    return jwt.encode(
        dict(claims), private_key, algorithm=algorithm, headers={"kid": kid}
    )


def _base64url(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode()


def _unsigned_segments(claims: Mapping[str, object], algorithm: str) -> str:
    header = {"alg": algorithm, "typ": "JWT", "kid": SIGNING_KID}
    return _encode_segments(header, claims)


def _encode_segments(header: Mapping[str, object], claims: Mapping[str, object]) -> str:
    return ".".join(
        _base64url(json.dumps(dict(part)).encode()) for part in (header, claims)
    )


def forge_token_with_header(
    header: Mapping[str, object], claims: Mapping[str, object]
) -> str:
    """Build a token with exactly the given header and an empty signature.

    ``jwt.encode`` refuses a header such as a numeric ``kid``, so a test that
    needs one assembles the segments itself.
    """
    return f"{_encode_segments(header, claims)}."


def forge_unsigned_token(claims: Mapping[str, object]) -> str:
    """Build a token that declares ``alg: none`` and carries no signature."""
    return f"{_unsigned_segments(claims, 'none')}."


def forge_hmac_token(claims: Mapping[str, object], private_key: RSAPrivateKey) -> str:
    """Build the key-confusion forgery: HS256 signed with the public key as secret.

    A verifier that lets the token header choose the algorithm would take the
    public key, which everybody can download, as an HMAC secret and accept this.
    """
    public_pem = private_key.public_key().public_bytes(
        serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo
    )
    signing_input = _unsigned_segments(claims, "HS256")
    digest = hmac.new(public_pem, signing_input.encode(), hashlib.sha256).digest()
    return f"{signing_input}.{_base64url(digest)}"


def make_token(**claim_overrides: object) -> str:
    """Sign valid claims with the tenant key; overrides follow ``valid_claims``."""
    return sign_token(valid_claims(**claim_overrides), tenant_signing_key())


class StubPublishedKey:
    """A published key, exposing ``key_id`` and ``key`` as ``jwt.PyJWK`` does."""

    def __init__(self, key_id: str, key: object) -> None:
        self.key_id = key_id
        self.key = key


class StubKeySource:
    """Key source that caches like ``PyJWKClient``, can fail, and records every load."""

    def __init__(
        self, public_keys: Mapping[str, object], *, error: Exception | None = None
    ) -> None:
        """Configure the source.

        Args:
            public_keys: Public keys by ``kid``.
            error: Raised for every load, to model an unreachable key endpoint.
        """
        self._public_keys = dict(public_keys)
        self.error = error
        self.loads: list[bool] = []
        self._cached: list[StubPublishedKey] | None = None

    def publish(self, key_id: str, key: object) -> None:
        """Add a key at the endpoint, as Entra does when it rotates its keys.

        A cached key set does not see it until a forced reload.
        """
        self._public_keys[key_id] = key

    @property
    def refreshes(self) -> int:
        """How many loads were forced past the cache."""
        return sum(self.loads)

    def get_signing_keys(self, refresh: bool = False) -> Sequence[StubPublishedKey]:
        """Return the cached keys, loading them first when needed or forced.

        Raises:
            PyJWKClientError: No key is published, as the real client reports.
        """
        if self._cached is None or refresh:
            self._cached = self._load(refresh)
        return self._cached

    def _load(self, refresh: bool) -> list[StubPublishedKey]:
        self.loads.append(refresh)
        if self.error is not None:
            raise self.error
        if not self._public_keys:
            raise PyJWKClientError("The JWKS endpoint did not contain any signing keys")
        return [StubPublishedKey(kid, key) for kid, key in self._public_keys.items()]


def tenant_key_source() -> StubKeySource:
    """Key source that publishes the tenant's public key under ``SIGNING_KID``."""
    return StubKeySource({SIGNING_KID: tenant_signing_key().public_key()})


def build_verifier(
    key_source: StubKeySource | None = None, **overrides: object
) -> EntraTokenVerifier:
    """Build a verifier for the test tenant over a stub key source.

    Args:
        key_source: Keys to serve; defaults to the tenant's published key.
        **overrides: Constructor arguments to replace.

    Returns:
        A verifier whose key lookups go through the real cooldown resolver.
    """
    source = key_source if key_source is not None else tenant_key_source()
    arguments: dict[str, object] = {
        "signing_keys": CooldownSigningKeyResolver(
            source, refresh_cooldown_seconds=REFRESH_COOLDOWN_SECONDS
        ),
        "tenant_id": TEST_TENANT_ID,
        "audiences": (TEST_API_CLIENT_ID, f"api://{TEST_API_CLIENT_ID}"),
        "issuer": ISSUER,
        "required_scope": SCOPE_NAME,
    }
    arguments.update(overrides)
    return EntraTokenVerifier(**arguments)
