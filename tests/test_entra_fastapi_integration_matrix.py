"""TDD guard for issue #14: JWKS-mocked FastAPI integration matrix.

Asserts that templates-entra-fastapi/api/tests/ ships:
  - entra_tokens.py: an RSA keypair generated by the test run, a token signer that
    puts the key id in the header, a stub key source that serves the public key,
    and ``build_verifier``, which puts that source behind the real
    ``CooldownSigningKeyResolver``, so no live network call is made
  - integration/test_auth.py: an ``integration``-marked module that swaps the
    verifier through ``dependency_overrides`` instead of patching a module-level
    JWKS client, and covers the full security matrix (valid→200+claims,
    bad-sig→401, wrong-aud→401, wrong-tid→401, missing-scp→403, key endpoint
    down→503, unknown kids→one reload), with the missing-header test intact

These tests run in the repo suite (testpaths = ["tests"]) and act as a red
gate that turns green once the overlay implementation is merged.
"""

import re
from pathlib import Path

_OVERLAY_TESTS = (
    Path(__file__).resolve().parent.parent
    / "project_initializer"
    / "templates-entra-fastapi"
    / "api"
    / "tests"
)

_JWKS_ADAPTER = (
    _OVERLAY_TESTS.parent / "app" / "infrastructure" / "auth" / "entra_jwks.py"
)
_TEST_AUTH = _OVERLAY_TESTS / "integration" / "test_auth.py"
_TOKENS = _OVERLAY_TESTS / "entra_tokens.py"

_NETWORK_IMPORTS = ("import httpx", "import requests", "import urllib", "import socket")


def _jwks_adapter_text() -> str:
    return _JWKS_ADAPTER.read_text(encoding="utf-8")


def _tokens_text() -> str:
    return _TOKENS.read_text(encoding="utf-8")


def _test_auth_text() -> str:
    return _TEST_AUTH.read_text(encoding="utf-8")


# ---------------------------------------------------------------------------
# Criterion: shared fixtures generate an RSA keypair, serve it through an
#            injected stub resolver, sign tokens with a kid header, no network call.
# ---------------------------------------------------------------------------


def test_when_overlay_tests_are_listed_then_the_token_helpers_and_the_matrix_exist():
    """when the overlay's test tree is inspected, the helpers and the matrix exist.

    The shared fixtures used to live in ``integration/conftest.py``; they now live
    in ``entra_tokens.py`` and in the ``use_entra_client`` fixture of test_auth.py.

    Validates project_initializer/templates-entra-fastapi/api/tests (entra_tokens.py and integration/test_auth.py).
    """
    assert _TOKENS.exists(), f"entra_tokens.py not found at {_TOKENS}"
    assert _TEST_AUTH.exists(), f"test_auth.py not found at {_TEST_AUTH}"
    assert not (_OVERLAY_TESTS / "integration" / "conftest.py").exists()


def test_when_token_helpers_read_then_rsa_private_key_generation_is_present():
    """when entra_tokens.py is read, it generates an RSA private key at run time.

    Validates project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py.
    """
    # cryptography library's RSA keygen function
    assert "generate_private_key" in _tokens_text()


def test_when_token_helpers_read_then_the_tenant_key_is_generated_once_per_process():
    """when entra_tokens.py is read, the tenant key is generated lazily and cached.

    RSA key generation is slow, so the key every test shares is built once.

    Validates project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py and project_initializer/templates-entra-fastapi/api/tests/integration/test_auth.py.
    """
    text = _tokens_text()
    assert re.search(r"^@cache\ndef tenant_signing_key\(", text, re.M)
    assert "return generate_signing_key()" in text
    assert "tenant_signing_key" in _test_auth_text()


def test_when_token_helpers_read_then_kid_header_is_used():
    """when entra_tokens.py is read, tokens are signed with a key id in the header.

    Validates project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py.
    """
    text = _tokens_text()
    assert "SIGNING_KID" in text
    assert '"kid"' in text


def test_when_token_helpers_read_then_the_verifier_gets_an_injected_resolver():
    """when entra_tokens.py is read, the verifier is built with an injected resolver.

    There is no module-level JWKS singleton any more, so nothing is patched: the
    verifier takes its ``signing_keys`` as a constructor argument, and the real
    cooldown resolver sits between it and the stub key source.

    Validates project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py and project_initializer/templates-entra-fastapi/api/tests/integration/test_auth.py.
    """
    text = _tokens_text()
    assert "EntraTokenVerifier(" in text
    assert "signing_keys" in text
    assert "CooldownSigningKeyResolver(" in text
    for module_text in (text, _test_auth_text()):
        assert "_jwks_client" not in module_text
        assert "monkeypatch" not in module_text


def test_when_test_auth_read_then_the_verifier_is_swapped_through_dependency_overrides():
    """when test_auth.py is read, it replaces the verifier dependency, not a module global.

    Validates project_initializer/templates-entra-fastapi/api/tests/integration/test_auth.py.
    """
    text = _test_auth_text()
    assert "app.dependency_overrides[get_token_verifier]" in text
    assert "build_verifier" in text


def test_when_token_helpers_read_then_the_stub_serves_keys_like_the_jwks_client():
    """when entra_tokens.py is read, the stub implements the slice of PyJWKClient used.

    The resolver in app/ reads ``get_signing_keys(refresh=...)`` from its key
    source and exposes ``get_signing_key_from_jwt`` to the verifier.

    Validates project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py and project_initializer/templates-entra-fastapi/api/app/infrastructure/auth/entra_jwks.py.
    """
    text = _tokens_text()
    assert "class StubKeySource" in text
    assert "def get_signing_keys" in text
    adapter = _jwks_adapter_text()
    assert "class CooldownSigningKeyResolver" in adapter
    assert "def get_signing_key_from_jwt" in adapter
    assert "def get_signing_keys" in adapter


def test_when_the_test_modules_are_read_then_no_live_discovery_endpoint_is_called():
    """when the helpers are read, they do not open the live Entra JWKS discovery URL.

    Validates project_initializer/templates-entra-fastapi/api/tests/integration/test_auth.py and project_initializer/templates-entra-fastapi/api/tests/entra_tokens.py.
    """
    # A mock fixture must not reach out to the real Entra key endpoint
    assert "login.microsoftonline.com" not in _test_auth_text()
    for text in (_test_auth_text(), _tokens_text()):
        assert "discovery" not in text
        assert "jwks_uri" not in text
        for network_import in _NETWORK_IMPORTS:
            assert network_import not in text


